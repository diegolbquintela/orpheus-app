// #176 (spec 50, Q-AO4 / Q-AO5): writes src/lib/finance/fonts/noto-sans-subset.ts from the committed subset .ttf files
// (base64, so the Vercel function bundles them with no vercel.json change). Run after changing a subset:
//   node scripts/gen-export-fonts.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../src/lib/finance/fonts/", import.meta.url);
const parts = ["// GENERATED by scripts/gen-export-fonts.mjs from the .ttf files next to this module. Do not edit.", "// Noto Sans subsets, SIL Open Font License 1.1 (see OFL.txt and FONTS.md in this folder).", ""];
for (const [name, file] of [["NOTO_SANS_REGULAR", "NotoSans-Regular-subset.ttf"], ["NOTO_SANS_BOLD", "NotoSans-Bold-subset.ttf"]]) {
  const bytes = readFileSync(new URL(file, dir));
  const b64 = bytes.toString("base64");
  parts.push(`/** ${file}: ${bytes.length} bytes, SHA-256 ${createHash("sha256").update(bytes).digest("hex")}. */`);
  parts.push(`export const ${name}_B64 =`);
  const lines = b64.match(/.{1,120}/g) ?? [];
  parts.push(lines.map((l, i) => `  "${l}"${i < lines.length - 1 ? " +" : ";"}`).join("\n"));
  parts.push("");
}
writeFileSync(new URL("noto-sans-subset.ts", dir), parts.join("\n"));
console.log("wrote noto-sans-subset.ts");
